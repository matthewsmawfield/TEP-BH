#!/usr/bin/env python3
"""Solve TEP interior on a regularised background.

Track 2 of the Bahrain v0.1 computational plan: confirm that a
temporal-well interior — regular centre, finite curvature, w_r -> -1 —
can coexist with the sGB temporal field on the temporal-well branch.

The geometric metric uses a Hayward-class regular mass function
    m(r) = M r^3 / (r^3 + g^3)
which is dynamically generated by an effective de-Sitter-like fluid
(w_r = -1) in the deep interior.  This is the minimal regularisation
that replaces the singular sGB centre with the TEP temporal well while
keeping the exterior weak-field limit unchanged.

The sGB scalar field φ(r) is then solved on this regular background
using the shift-symmetric coupling, and the TEP matter metric
    dŝ^2 = A(φ)^2 ds^2 + B(φ) ∇φ ∇φ
is constructed.  The code checks that the matter metric has a regular
centre, Lorentzian signature, and a positive minimum lapse.

Boundary-value formulation (corrected method)
---------------------------------------------
The scalar problem is the two-point boundary-value problem

    □φ = -alpha_GB f'(φ) 𝒢[g],
    φ'(0) = 0                 (regular centre),
    φ(r) -> 0  as r -> ∞      (ambient-time normalisation, Rule 4),

solved by outward shooting from the regular-centre expansion with a root
find on φ(0) = φ_c so that the non-decaying tail coefficient vanishes.

Source sign.  For the temporal-well branch the exterior tail is the
positive-charge decaying profile φ ~ +Q_s/r (Q_s = 2α_GB/M > 0 for
η > 0).  Since the radial equation integrates as
(r^2 N^2 φ')' = r^2 · src, a decaying tail (φ' < 0) requires a negative
integrated source, i.e. src = -α_GB f'𝒢.  This is the standard EdGB
sign for the temporal-well branch; the opposite sign produces a
negative-charge anti-well (φ < 0, A > 1), inconsistent with Rule 4.

Correction note.  The previous version of this step integrated an inward
initial-value problem from the matching radius using a negated
right-hand side.  That scheme solves the friction-reversed equation
φ'' = src/N^2 + (2/r + N'/N) φ', for which inward integration artificially
damps the Coulomb homogeneous mode; the true inward IVP of the stated
equation diverges as φ ~ C/r — exterior matching data do not lie on the
regular-centre branch.  The reported regular centre was therefore an
artefact of the sign-flipped friction.  The regular solution is a
boundary-value problem and is computed here by outward integration.
The divergent direct inward IVP is retained below as
`diagnostic_inward_ivp` to document the Coulomb branch explicitly.

Source models for 𝒢.
    * ``gb_invariant`` — the declared benchmark convention: the
      Schwarzschild-form invariant 48 m(r)^2/r^6 evaluated on the
      regularised mass function.  This is the smooth inward continuation
      of the exterior sGB source and is the convention shared by
      steps 29/30.
    * ``gb_invariant_exact`` — the exact Gauss–Bonnet scalar of the
      prescribed Hayward background, including the Ricci-sector
      contributions inside the de Sitter core.  It changes sign across an
      interior shell and screens the exterior scalar charge; it is
      computed as a sensitivity branch.

Outputs:
    results/step_34_solve_interior.json
"""

