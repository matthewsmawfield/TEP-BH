# ---------------------------------------------------------------------------
# Background geometry: Hayward-class regular metric
# ---------------------------------------------------------------------------
def hayward_mass(r, M, g):
    """Hayward mass function: m(r) = M r^3 / (r^3 + g^3)."""
    return M * r**3 / (r**3 + g**3)


def hayward_lapse_sq(r, M, g):
    """N^2(r) = 1 - 2 m(r) / r."""
    return 1.0 - 2.0 * hayward_mass(r, M, g) / r


def hayward_N(r, M, g):
    return np.sqrt(np.maximum(hayward_lapse_sq(r, M, g), 1e-14))


def hayward_dNdr(r, M, g):
    """Derivative of N(r) for the Hayward metric."""
    m = hayward_mass(r, M, g)
    m_p = 3.0 * M * g**3 * r**2 / (r**3 + g**3) ** 2
    f = 1.0 - 2.0 * m / r
    # d(N^2)/dr = -2 (m' r - m)/r^2
    # 2 N N' = -2 (m' r - m)/r^2
    # N' = (m - m' r) / (N r^2)
    N = np.sqrt(np.maximum(f, 1e-14))
    return (m - m_p * r) / (N * r**2 + 1e-30)


def hayward_fp(r, M, g):
    """f'(r) for f = N^2 = 1 - 2M r^2/(r^3 + g^3)."""
    D = r**3 + g**3
    return -2.0 * M * r * (2.0 * g**3 - r**3) / D**2


def hayward_fpp(r, M, g):
    """f''(r) for f = N^2 = 1 - 2M r^2/(r^3 + g^3)."""
    D = r**3 + g**3
    return -4.0 * M * (r**6 - 7.0 * r**3 * g**3 + g**6) / D**3


# ---------------------------------------------------------------------------
# Curvature invariants
# ---------------------------------------------------------------------------
def gb_invariant(r, M, g):
    """Leading Gauss-Bonnet invariant on a Schwarzschild-like background.

    G_GB = 48 m(r)^2 / r^6 — the vacuum (Schwarzschild) form evaluated on
    the regularised mass function.  This is the declared benchmark source
    convention, shared with the exterior sGB benchmark and steps 29/30.
    """
    m = hayward_mass(r, M, g)
    return 48.0 * m**2 / r**6


def gb_invariant_exact(r, M, g):
    """Exact Gauss-Bonnet scalar of the prescribed Hayward background.

    For ds^2 = -f dt^2 + dr^2/f + r^2 dΩ^2 the orthonormal-frame
    contraction gives, with Einstein-tensor components
    G^t_t = G^r_r = (f-1)/r^2 + f'/r,  G^θ_θ = G^φ_φ = f''/2 + f'/r:

        R     = -2(G^t_t + G^θ_θ)
        Ric^2 = 2(G^t_t + R/2)^2 + 2(G^θ_θ + R/2)^2
        K     = 4(f''/2)^2 + 16(f'/2r)^2 + 4((1-f)/r^2)^2
        𝒢     = R^2 - 4 Ric^2 + K.

    At the de Sitter core this reduces to 𝒢(0) = 96 M^2/g^6
    (= 24 H^4 with H^2 = 2M/g^3); at large r it recovers 48 M^2/r^6.
    Inside the matter region it includes the Ricci-sector terms absent
    from the vacuum form and changes sign across an interior shell.
    """
    f = hayward_lapse_sq(r, M, g)
    fp = hayward_fp(r, M, g)
    fpp = hayward_fpp(r, M, g)

    R_trtr = -fpp / 2.0
    R_titi = -fp / (2.0 * r)
    R_riri = fp / (2.0 * r)
    R_thth = (1.0 - f) / r**2
    K = 4.0 * R_trtr**2 + 8.0 * R_titi**2 + 8.0 * R_riri**2 + 4.0 * R_thth**2

    G_t = (f - 1.0) / r**2 + fp / r
    G_th = fpp / 2.0 + fp / r
    R_scalar = -2.0 * (G_t + G_th)
    Ric2 = 2.0 * (G_t + R_scalar / 2.0) ** 2 + 2.0 * (G_th + R_scalar / 2.0) ** 2

    return R_scalar**2 - 4.0 * Ric2 + K


def kretschmann_exact(r, M, g):
    """Exact Kretschmann scalar of the prescribed Hayward background.

    K(0) = 96 M^2/g^6 = 24 H^4 at the de Sitter core; K -> 48 M^2/r^6
    in the exterior.
    """
    f = hayward_lapse_sq(r, M, g)
    fp = hayward_fp(r, M, g)
    fpp = hayward_fpp(r, M, g)
    R_trtr = -fpp / 2.0
    R_titi = -fp / (2.0 * r)
    R_riri = fp / (2.0 * r)
    R_thth = (1.0 - f) / r**2
    return 4.0 * R_trtr**2 + 8.0 * R_titi**2 + 8.0 * R_riri**2 + 4.0 * R_thth**2


# ---------------------------------------------------------------------------
# Scalar field on the regular background
# ---------------------------------------------------------------------------
def sgb_scalar_exterior(r, M, eta):
    """Sotiriou-Zhou sGB scalar profile (exterior EFT)."""
    Q_s = 2.0 * eta * M / 3.0
    return Q_s * (1.0 / r + M / r**2 + 4.0 * M**2 / (3.0 * r**3))


def sgb_scalar_exterior_derivative(r, M, eta):
    """Radial derivative of the exterior sGB scalar profile."""
    Q_s = 2.0 * eta * M / 3.0
    return Q_s * (-1.0 / r**2 - 2.0 * M / r**3 - 4.0 * M**2 / r**4)


def scalar_equation(r, y, M, eta, g, f_of_phi, df_of_phi, gb_fn=None):
    """ODE for φ on the regular background: y = [φ, φ'].

    Metric: ds^2 = -N^2 dt^2 + N^{-2} dr^2 + r^2 dΩ^2.  For a static
    spherical scalar the d'Alembertian is
        □φ = (1 / r^2) d/dr (r^2 N^2 φ')
           = N^2 φ'' + (2 N^2 / r + 2 N N') φ',
    so the field equation □φ = -alpha_GB f'(φ) 𝒢 gives
        φ'' = src / N^2 - (2/r + 2 N'/N) φ',   src = -alpha_GB f'(φ) 𝒢.

    The negative source sign is the standard EdGB convention for the
    temporal-well branch and is the unique sign consistent with the
    positive-charge decaying exterior φ ~ +Q_s/r: with φ'(0) = 0 the
    integrated equation r^2 N^2 φ' = ∫ r'^2 src dr' must go negative for
    a decaying tail.

    gb_fn selects the GB source model (default: the declared
    Schwarzschild-form benchmark ``gb_invariant``).
    """
    if gb_fn is None:
        gb_fn = gb_invariant
    phi, phi_p = y
    if r < 1e-14:
        return [0.0, 0.0]

    N = hayward_N(r, M, g)
    N_p = hayward_dNdr(r, M, g)

    alpha_GB = eta * M**2 / 3.0
    G = gb_fn(r, M, g)
    source = -alpha_GB * df_of_phi(phi) * G

    dphi_pp = source / N**2 - (2.0 / r + 2.0 * N_p / N) * phi_p
    return [phi_p, dphi_pp]


# ---------------------------------------------------------------------------
# Couplings
# ---------------------------------------------------------------------------
def conformal_factor(phi, beta_A=-1.0):
    return np.exp(beta_A * phi)


def disformal_function(phi, B0=1.0, sigma_B=1.5, n_B=2.0):
    """Ultra-damped quartic Gaussian envelope for B(φ)."""
    abs_phi = np.abs(phi)
    return B0 * (abs_phi**n_B / (1.0 + abs_phi**n_B)) * np.exp(-abs_phi**4 / sigma_B**4)


def linear_f(phi):
    return phi


def d_linear_f(phi):
    return 1.0


def nonlinear_f(phi, phi0=1.0):
    """Saturation function: f(φ) = φ / (1 + (φ/φ0)^2)."""
    return phi / (1.0 + (phi / phi0) ** 2)


def d_nonlinear_f(phi, phi0=1.0):
    x = phi / phi0
    return (1.0 - x**2) / (1.0 + x**2) ** 2


# ---------------------------------------------------------------------------
# Regular-centre boundary value problem
# ---------------------------------------------------------------------------
def _shoot_outward(phi_c, M, eta, g, f_of_phi, df_of_phi, gb_fn,
                   r_eps=1e-6, r_max=1e5, rtol=1e-9):
    """Integrate the scalar equation outward from the regular centre.

    Regular-centre expansion: with φ'(0) = 0 and src(0) = src_0,
    φ(r) = φ_c + φ_2 r^2 + O(r^4) where φ_2 = src_0 / (6 N(0)^2)
    (from φ'' = src/N^2 - (2/r + 2N'/N) φ' as r -> 0).
    """
    alpha_GB = eta * M**2 / 3.0
    src0 = -alpha_GB * df_of_phi(phi_c) * gb_fn(r_eps, M, g)
    phi2 = src0 / (6.0 * hayward_lapse_sq(r_eps, M, g))
    y0 = [phi_c + phi2 * r_eps**2, 2.0 * phi2 * r_eps]
    sol = solve_ivp(
        lambda r, y: scalar_equation(r, y, M, eta, g, f_of_phi, df_of_phi, gb_fn),
        [r_eps, r_max],
        y0,
        method="Radau",
        dense_output=True,
        rtol=rtol,
        atol=1e-11,
    )
    return sol


def _tail_coefficients(sol, r1, r2):
    """Fit phi ~ a + b/r on [r1, r2]; return (a, b) with b = Q_eff."""
    p1, p2 = sol.sol(r1)[0], sol.sol(r2)[0]
    b = (p1 - p2) / (1.0 / r1 - 1.0 / r2)
    a = p1 - b / r1
    return a, b


def solve_scalar_bvp(M, eta, g, f_of_phi, df_of_phi, gb_fn=None,
                     r_eps=1e-6, r_max=1e5, phi_c_hi=50.0, n_scan=50):
    """Solve the regular-centre BVP: φ'(0)=0, φ(∞)=0.

    Scans φ_c over [0, phi_c_hi], root-finds the decaying-tail condition
    a(φ_c) = 0 where φ ~ a + Q_eff/r at large r.  Returns the solution
    object plus the central value and tail coefficients.  The smallest
    positive root is taken when several exist.
    """
    if gb_fn is None:
        gb_fn = gb_invariant

    def tail_a(phi_c):
        sol = _shoot_outward(phi_c, M, eta, g, f_of_phi, df_of_phi, gb_fn,
                             r_eps=r_eps, r_max=r_max)
        a, _ = _tail_coefficients(sol, r_max / 2.0, r_max)
        return a, sol

    xs = np.linspace(1e-4, phi_c_hi, n_scan)
    roots = []
    prev = None
    for x in xs:
        try:
            v, _ = tail_a(x)
        except Exception:
            v = np.nan
        if prev is not None and np.isfinite(v) and np.isfinite(prev[0]) and v * prev[0] < 0:
            lo, hi = prev[1], x
            root = brentq(lambda pc: tail_a(pc)[0], lo, hi, xtol=1e-9, rtol=1e-9)
            roots.append(root)
        prev = (v, x)

    if not roots:
        return None

    phi_c = roots[0]
    sol = _shoot_outward(phi_c, M, eta, g, f_of_phi, df_of_phi, gb_fn,
                         r_eps=r_eps, r_max=r_max)
    a, Q_eff = _tail_coefficients(sol, r_max / 2.0, r_max)
    return {"sol": sol, "phi_c": phi_c, "tail_a": a, "Q_eff": Q_eff}


def diagnostic_inward_ivp(M, eta, g, f_of_phi, df_of_phi, gb_fn=None,
                          r_match=10.0, r_min=1e-6):
    """Direct inward IVP of the stated scalar equation from the SZ data.

    Documents the Coulomb divergence of the inward initial-value problem:
    the exterior matching data do not lie on the regular-centre branch, so
    the regular solution must be obtained as a two-point BVP.  This is the
    computation the previous version approximated with a sign-flipped
    (friction-reversed) right-hand side.
    """
    if gb_fn is None:
        gb_fn = gb_invariant
    phi0 = sgb_scalar_exterior(r_match, M, eta)
    phi_p0 = sgb_scalar_exterior_derivative(r_match, M, eta)
    r_grid = np.geomspace(r_match, r_min, 400)
    sol = solve_ivp(
        lambda r, y: scalar_equation(r, y, M, eta, g, f_of_phi, df_of_phi, gb_fn),
        [r_match, r_min],
        [phi0, phi_p0],
        method="Radau",
        t_eval=r_grid,
        rtol=1e-9,
        atol=1e-11,
    )
    return sol


# ---------------------------------------------------------------------------
# Diagnostics
# ---------------------------------------------------------------------------
def analyse(r, phi, phi_p, M, eta, g, gb_fn=None, label=""):
    """Diagnostics for a solved scalar profile on the regular background."""
    if gb_fn is None:
        gb_fn = gb_invariant
    N = hayward_N(r, M, g)
    m = hayward_mass(r, M, g)

    A = conformal_factor(phi)
    B = disformal_function(phi)

    # Matter metric lapse and radial component
    # dŝ^2 = A^2 (-N^2 dt^2 + N^{-2} dr^2 + r^2 dΩ^2) + B φ'^2 dr^2
    N_tilde = A * N
    g_rr_tilde = A**2 / N**2 + B * phi_p**2

    # Areal radius of matter metric
    rho_areal = A * r

    # Effective fluid w_r from the background metric (should be -1 for Hayward)
    rho_eff = np.where(r > 0, m / (4.0 / 3.0 * np.pi * r**3 + 1e-30), 1e-30)
    p_eff = -rho_eff
    w_r = p_eff / rho_eff

    # Exact Kretschmann scalar of the Hayward background
    K = np.array([kretschmann_exact(rr, M, g) for rr in r])

    # Lorentzianity: g_rr_tilde > 0 and N_tilde > 0
    lorentzian = np.all(g_rr_tilde > 1e-12) and np.all(N_tilde > 1e-12)

    i_N_min = int(np.argmin(N))
    i_Nt_min = int(np.argmin(N_tilde))
    i_K_max = int(np.argmax(K))

    # Maximum transfer factor for an ambient observer (N_o -> 1)
    T_max = float(1.0 / N_tilde[i_Nt_min])

    # Scalar monotonicity (temporal-well branch: φ decreasing outward)
    monotone_well = bool(np.all(phi_p <= 1e-4))

    i_c = 0  # grid is ascending from the centre
    return {
        "label": label,
        "r_centre": float(r[i_c]),
        "phi_centre": float(phi[i_c]),
        "phi_pp_centre": float(phi_p[i_c]),
        "A_centre": float(A[i_c]),
        "N_centre": float(N[i_c]),
        "N_tilde_centre": float(N_tilde[i_c]),
        "g_rr_tilde_centre": float(g_rr_tilde[i_c]),
        "rho_areal_centre": float(rho_areal[i_c]),
        "w_r_centre": float(w_r[i_c]),
        "K_centre": float(K[i_c]),
        "N_min": float(N[i_N_min]),
        "r_N_min": float(r[i_N_min]),
        "N_tilde_min": float(N_tilde[i_Nt_min]),
        "r_N_tilde_min": float(r[i_Nt_min]),
        "T_max": T_max,
        "K_max": float(K[i_K_max]),
        "r_K_max": float(r[i_K_max]),
        "monotone_well": monotone_well,
        "lorentzian": bool(lorentzian),
        "regular": bool(
            lorentzian
            and A[i_c] > 1e-12
            and np.isfinite(K[i_c])
            and rho_areal[i_c] < 1e-2
            and abs(phi_p[i_c]) < 1e-2
        ),
        # backward-compatible aliases used by downstream steps
        "r_final": float(r[i_c]),
        "phi_final": float(phi[i_c]),
        "A_final": float(A[i_c]),
        "N_final": float(N[i_c]),
        "N_tilde_final": float(N_tilde[i_c]),
        "rho_areal_final": float(rho_areal[i_c]),
        "w_r_final": float(w_r[i_c]),
        "K_final": float(K[i_c]),
        "phi_p_final": float(phi_p[i_c]),
    }


