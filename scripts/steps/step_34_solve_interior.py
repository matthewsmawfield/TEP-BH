def main():
    M = 1.0
    eta = 0.3  # temporal-well branch; interior regularity floor |alpha_GB|/M^2 >= 0.1 (step_33, Paper 0)
    r_match = 10.0 * M
    r_min = 1e-8 * M

    # Hayward core size.  g > M keeps the lapse real everywhere.
    g_values = [1.1, 1.5, 2.0]
    gb_models = {
        "schwarzschild_form": gb_invariant,        # declared benchmark source
        "hayward_exact": gb_invariant_exact,       # exact background GB (sensitivity)
    }

    print("=" * 70)
    print("TEP INTERIOR SOLVER — TEMPORAL WELL ON HAYWARD-CLASS METRIC")
    print("=" * 70)
    print("  Boundary-value problem: phi'(0)=0 (regular centre), phi->0 at infinity")
    print("  Scalar equation: □φ = -alpha_GB f'(φ) 𝒢  (temporal-well EdGB sign)")
    print(f"  M       = {M}")
    print(f"  eta     = {eta}  (temporal-well branch)")
    print(f"  r_match = {r_match} M   (diagnostic comparison to SZ exterior)")
    print()

    # --- method validation: the direct inward IVP diverges (Coulomb branch) ---
    print("Method validation — direct inward IVP of the stated equation:")
    sol_ivp = diagnostic_inward_ivp(M, eta, g_values[0], linear_f, d_linear_f)
    rr_ivp = sol_ivp.t
    phi_ivp = sol_ivp.y[0]
    c_eff = float(phi_ivp[-1] * rr_ivp[-1])  # phi ~ C/r => C = r*phi
    print(f"  inward IVP: phi(r_min={rr_ivp[-1]:.0e}) = {phi_ivp[-1]:.3e}, "
          f"r*phi -> {c_eff:.3f}  (Coulomb divergence; regular branch needs BVP)")
    print()

    results = {}
    scan_meta = {}

    for g in g_values:
        entry = {}
        for coupling_name, f_of_phi, df_of_phi in [
            ("linear", linear_f, d_linear_f),
            ("nonlinear_phi0_0.5",
             lambda p: nonlinear_f(p, phi0=0.5),
             lambda p: d_nonlinear_f(p, phi0=0.5)),
        ]:
            coupling_entry = {}
            for gb_name, gb_fn in gb_models.items():
                bvp = solve_scalar_bvp(M, eta, g, f_of_phi, df_of_phi, gb_fn)
                if bvp is None:
                    print(f"  g={g} {coupling_name} {gb_name}: no decaying root found")
                    continue
                sol = bvp["sol"]
                r_prof = np.geomspace(1e-6, 300.0, 4000)
                prof = sol.sol(r_prof)
                diag = analyse(r_prof, prof[0], prof[1], M, eta, g, gb_fn,
                               label=f"{coupling_name}|{gb_name}")
                diag["phi_c"] = bvp["phi_c"]
                diag["tail_a_residual"] = bvp["tail_a"]
                diag["Q_eff"] = bvp["Q_eff"]
                diag["phi_at_r_match"] = float(sol.sol(r_match)[0])
                diag["phi_p_at_r_match"] = float(sol.sol(r_match)[1])
                diag["phi_sz_at_r_match"] = float(sgb_scalar_exterior(r_match, M, eta))
                diag["Q_s_sz"] = 2.0 * eta * M / 3.0
                coupling_entry[gb_name] = diag
                print(
                    f"  g={g:.2f} {coupling_name:18s} {gb_name:17s}: "
                    f"phi_c={bvp['phi_c']:8.4f} A(0)={diag['A_centre']:.3e} "
                    f"N_tilde_min={diag['N_tilde_min']:.4e}@r={diag['r_N_tilde_min']:.3f} "
                    f"T_max={diag['T_max']:9.3f} Q_eff={diag['Q_eff']:+.3f} "
                    f"mono={diag['monotone_well']} regular={diag['regular']}"
                )
            entry[coupling_name] = coupling_entry
        results[f"g_{g}"] = entry
        print()

    # Primary benchmark: declared source convention (Schwarzschild-form GB),
    # linear coupling, deepest well (g = 1.1).
    g_best = g_values[0]
    diag_best = results[f"g_{g_best}"]["linear"]["schwarzschild_form"]

    print("=" * 70)
    print("PRIMARY BENCHMARK (linear coupling, Schwarzschild-form source, g=1.1)")
    print("=" * 70)
    print(f"  Regular:        {diag_best['regular']}")
    print(f"  phi(centre)     = {diag_best['phi_c']:.6f}")
